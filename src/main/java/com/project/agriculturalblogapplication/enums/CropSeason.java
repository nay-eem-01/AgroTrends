package com.project.agriculturalblogapplication.enums;

/** Bangladesh's cropping seasons. */
public enum CropSeason {
    /** Winter, roughly mid-October to mid-March (wheat, mustard, potato, boro rice). */
    RABI,
    /** Pre-monsoon, roughly mid-March to mid-July (aus rice, jute). */
    KHARIF_1,
    /** Monsoon, roughly mid-July to mid-October (aman rice). */
    KHARIF_2,
    YEAR_ROUND
}
